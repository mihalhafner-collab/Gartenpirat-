"""Project public maintenance phrases into a small offline script for WebView.

The JSON catalog stays the only editable source; this creates no operating rows.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'android/app/src/main/assets/equipment-maintenance-texts.json'
TARGET = SOURCE.with_suffix('.js')

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    catalog = json.loads(SOURCE.read_text())
    phrases = [{'id': row['id'], 'label': row['label'], 'text': row['text']}
               for row in catalog['actions']]
    if len({row['id'] for row in phrases}) != len(phrases):
        raise SystemExit('Duplicate maintenance phrase')
    content = ('/* Generated by tools/sync_equipment_maintenance_texts.py; edit JSON. */\n'
               'window.HGEquipmentMaintenanceTexts=Object.freeze('
               + json.dumps(phrases, ensure_ascii=False, separators=(',', ':'))
               .replace('<', '\\u003c').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
               + ');\n')
    if args.check:
        if not TARGET.is_file() or TARGET.read_text() != content:
            raise SystemExit('Maintenance phrases mirror is stale')
    else:
        TARGET.write_text(content)
    print(f'PASS {len(phrases)} public offline maintenance phrases')

if __name__ == '__main__':
    main()
