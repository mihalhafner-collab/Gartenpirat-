const assert = require('node:assert/strict');
const fs = require('node:fs');
require('../static/invoice-editor.js');
const ui = globalThis.InvoiceStudio;
const p = (quantity,price,discount=0) => ({quantity,price,discount,title:'Gartenpflege',unit:'Std.',tax_rate:0});
assert.equal(ui.lineCents(p('1','0.105')),11);
assert.equal(ui.lineCents(p('1','1.005')),101);
assert.equal(ui.lineCents(p('2.5','50','10')),11250);
assert.equal(ui.lineCents(p('1,5','25,10')),3765);
assert.equal(ui.total([p('1','0.105'),p('1','0.105')]),0.22);
assert.throws(()=>ui.lineCents(p('0','50')));
assert.throws(()=>ui.lineCents(p('2','NaN')));
assert.throws(()=>ui.lineCents({...p('1','50'),tax_rate:20}));
assert.throws(()=>ui.lineCents(p('1','50',101)));
assert.equal(ui.dueDate('2026-12-25',14),'2027-01-08');
assert.equal(ui.dueDate('2026-02-30',14),'');
assert.equal(ui.dueDate('2026-10-08',-1),'');
const draft={invoice_number:'Entwurf-123',invoice_date:'2026-10-08',service_start:'2026-10-01',service_end:'2026-10-01',payment_days:14,positions:[{...p('3','50'),description:'Pflege <script>alert(1)</script>',title:'Hecke & Garten'}],notes:'INTERNE-NOTIZ-NICHT-ZEIGEN'};
const before=JSON.stringify(draft);
const html=ui.preview(draft,{owner_name:'Hafner Michael'}, {name:'Testkunde',street:'Gartenweg 1',city:'Glanegg',postal_code:'9555'},'hafner-logo.png');
assert.match(html,/ENTWURF/);
assert.match(html,/Hecke &amp; Garten/);
assert.match(html,/&lt;script&gt;/);
assert.doesNotMatch(html,/<script>/);
assert.doesNotMatch(html,/INTERNE-NOTIZ-NICHT-ZEIGEN/);
assert.doesNotMatch(html,/Entwurf-123/);
assert.equal(JSON.stringify(draft),before);
assert.match(ui.preview({...draft,positions:[p('0','50')]}),/Bitte prüfen/);
assert.equal(fs.readFileSync('static/invoice-editor.js','utf8'),fs.readFileSync('android/app/src/main/assets/invoice-editor.js','utf8'));
assert.equal(fs.readFileSync('static/invoice-editor.css','utf8'),fs.readFileSync('android/app/src/main/assets/invoice-editor.css','utf8'));
console.log('22 Prüfungen: gemeinsame Rechnungsvorschau, Rundung, Eingaben, Datenschutz und identische Android-/Laptop-Dateien bestanden.');
